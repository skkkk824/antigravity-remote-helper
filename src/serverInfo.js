'use strict';

const fs = require('fs');
const path = require('path');

/**
 * Read Antigravity IDE server config from `product.json` inside `appRoot`.
 * Mirrors `getVSCodeServerConfig()` in `antigravity-remote-openssh`.
 * @param {string} appRoot
 * @param {string} vscodeVersion
 * @param {string} [overrideBinaryName]
 * @returns {{vscodeVersion: string, ideVersion: string, commit: string, quality: string, serverApplicationName: string, serverDataFolderName: string, distroId: string, isDevelopment: boolean}}
 */
function readServerConfigFromAppRoot(appRoot, vscodeVersion, overrideBinaryName) {
  const productPath = path.join(appRoot, 'product.json');
  const product = JSON.parse(fs.readFileSync(productPath, 'utf8'));

  const cleanVsCodeVersion = (vscodeVersion || '').replace('-insider', '');
  let ideVersion = product.ideVersion;
  let commit = product.commit;
  let quality = product.quality || 'stable';
  let serverApplicationName =
    (overrideBinaryName || '').trim() || product.serverApplicationName || 'antigravity-ide-server';
  let serverDataFolderName = product.serverDataFolderName || '.antigravity-ide-server';
  let isDevelopment = false;

  if (quality === 'dev') {
    ideVersion = 'development';
    commit = 'samplecommit';
    quality = 'insider';
    serverApplicationName = (overrideBinaryName || '').trim() || 'antigravity-ide-server-insiders';
    serverDataFolderName = '.antigravity-ide-server-insiders';
    isDevelopment = true;
  }

  const distroId = commit + (isDevelopment ? '-dev' : '');

  return {
    vscodeVersion: cleanVsCodeVersion,
    ideVersion,
    commit,
    quality,
    serverApplicationName,
    serverDataFolderName,
    distroId,
    isDevelopment,
  };
}

/**
 * Map `uname -s` and `uname -m` from the remote host to Antigravity server platform & arch.
 * Matches the remote bash script generated by `antigravity-remote-openssh`.
 * @param {string} unameKernel
 * @param {string} unameMachine
 * @returns {{platform: string, serverArch: string, archiveName: string}}
 */
function mapRemotePlatform(unameKernel, unameMachine) {
  const kernel = (unameKernel || '').trim();
  const machine = (unameMachine || '').trim();

  let platform;
  if (kernel === 'Linux') platform = 'linux';
  else if (kernel === 'Darwin') platform = 'darwin';
  else throw new Error(`Unsupported remote OS kernel: ${kernel}`);

  let serverArch;
  if (machine === 'x86_64' || machine === 'amd64') serverArch = 'x64';
  else if (machine === 'armv7l' || machine === 'armv8l') serverArch = 'armhf';
  else if (machine === 'arm64' || machine === 'aarch64') serverArch = 'arm';
  else if (machine === 'ppc64le') serverArch = 'ppc64le';
  else if (machine === 'riscv64') serverArch = 'riscv64';
  else throw new Error(`Unsupported remote architecture: ${machine}`);

  return { platform, serverArch };
}

/**
 * Build archive name and official Google CDN mirror URLs for a given config and target platform.
 * @param {{quality: string, ideVersion: string, commit: string}} serverConfig
 * @param {string} platform
 * @param {string} serverArch
 * @returns {{archiveName: string, urls: string[]}}
 */
function buildDownloadUrls(serverConfig, platform, serverArch) {
  const archiveName =
    serverConfig.quality === 'insider'
      ? 'Antigravity IDE - Insiders-reh.tar.gz'
      : 'Antigravity IDE-reh.tar.gz';

  const relPath = `${serverConfig.quality}/${serverConfig.ideVersion}-${serverConfig.commit}/${platform}-${serverArch}/${encodeURIComponent(archiveName)}`;

  return {
    archiveName,
    urls: [
      `https://edgedl.me.gvt1.com/edgedl/release2/j0qc3/antigravity/${relPath}`,
      `https://redirector.gvt1.com/edgedl/release2/j0qc3/antigravity/${relPath}`,
      `https://edgedl.me.gvt1.com/edgedl/antigravity/${relPath}`,
      `https://redirector.gvt1.com/edgedl/antigravity/${relPath}`,
    ],
  };
}

/**
 * Compute remote paths for server installation.
 * @param {string} remoteHome
 * @param {{serverDataFolderName: string, ideVersion: string, distroId: string, serverApplicationName: string}} serverConfig
 * @returns {{serverDataDir: string, serverDir: string, serverScript: string, lockFile: string}}
 */
function getRemotePaths(remoteHome, serverConfig) {
  const home = remoteHome.replace(/\/+$/, '');
  const serverDataDir = `${home}/${serverConfig.serverDataFolderName}`;
  const serverDir = `${serverDataDir}/bin/${serverConfig.ideVersion}-${serverConfig.distroId}`;
  const serverScript = `${serverDir}/bin/${serverConfig.serverApplicationName}`;
  const lockFile = `${serverDataDir}/.installation_lock`;
  return { serverDataDir, serverDir, serverScript, lockFile };
}

module.exports = {
  readServerConfigFromAppRoot,
  mapRemotePlatform,
  buildDownloadUrls,
  getRemotePaths,
};
